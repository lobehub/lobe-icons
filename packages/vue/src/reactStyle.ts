export function normalizeReactStyleValue(property: string, value: number): number | string;
export function normalizeReactStyleValue<T>(property: string, value: T): T;
export function normalizeReactStyleValue(property: string, value: unknown): unknown {
  return typeof value === 'number' &&
    value !== 0 &&
    !property.startsWith('--') &&
    !unitlessProperties.has(property)
    ? `${value}px`
    : value;
}
